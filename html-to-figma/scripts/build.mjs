// Inlines src/capture.js into the plugin UI (Figma UIs must be a single HTML file).
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const capture = await readFile(new URL('src/capture.js', root), 'utf8');
if (/<\/script/i.test(capture)) throw new Error('capture.js must not contain "</script"');
const template = await readFile(new URL('plugin/ui.template.html', root), 'utf8');
const html = template.replace('/*__CAPTURE_JS__*/', () => capture);
await writeFile(new URL('plugin/ui.html', root), '<!-- Generated by scripts/build.mjs from ui.template.html. Do not edit. -->\n' + html);
console.log('plugin/ui.html built');
